#!/usr/bin/env python3
"""Keep this anthology in step with the Proven-Commons org.

Run from the repo root:

    python3 scripts/sync.py [--check] [--report FILE] [--keep-pin REPO ...] [--hold-joint [REPO ...]]
                            [--save-found FILE | --found FILE]
    python3 scripts/sync.py --render

The default run lists every public repo in the org, fetches the head of
each one's default branch, decides which repos can join the workspace,
writes what it found to repos.json, and renders the files made from it:
lakefile.toml, lean-toolchain, Anthology.lean, AnthologyProofs.lean and
the generated block of README.md. After it, run `lake update` to
regenerate lake-manifest.json, build, and run scripts/audit.py.

--check writes nothing, and exits 1 if a sync would change any file.
--render needs no network: it renders from the committed repos.json and
audit.json. --report writes a Markdown summary of the changes, for a
pull request. --keep-pin names repos whose default branch head fails to
build: each keeps its current pin, or stays out of the workspace if it has
none. --hold-joint names repos whose proof library AnthologyProofs
leaves out because the joint proof build fails with it: two packages can
declare the same theorem name even when their module names differ.
Without --hold-joint, a library held out before stays out while its pin
does not move, so an unchanged upstream reproduces the last state;
--hold-joint with no names tries every one again. --save-found
writes what was read from upstream to a file, and --found reads it back
instead of reading upstream again, so that later decisions in one sync
see the same upstream. --previous names the repos.json to compare with
(default: the one in the repo).

A repo joins the workspace when its default branch has a lakefile.toml
and a lean-toolchain, it uses the workspace toolchain, and every
top-level module name its main library imports is its own. A repo that
is already in the workspace and whose new head cannot join keeps its
current pin, with the reason. README.md, "How it stays up to date", has
the full rules.

Needs Python 3.11 or later, git, and nothing outside the standard
library. Reads GITHUB_TOKEN, if set, to list the org's repos.
"""
