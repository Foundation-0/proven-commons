# Module names this repo defines itself.
OWN_MODULES = {"Anthology", "AnthologyProofs"}
TOOLCHAIN = re.compile(r"leanprover/lean4:v(\d+)\.(\d+)\.(\d+)(?:-rc(\d+))?")
GENERATED = "Generated by scripts/sync.py from repos.json. Do not edit by hand."


def load_config():
    cfg = tomllib.loads(CONFIG.read_text())
    cfg.setdefault("exclude", [])
    cfg.setdefault("hold", {})
    return cfg


def git_base(cfg):
    # Tests point this at local fixture repos.
    return os.environ.get("SYNC_GIT_BASE") or f"https://github.com/{cfg['org']}"


# Listing the org ------------------------------------------------------

def list_org(org, repos_file=None):
    """Every public repo in the org: name, description, default branch,
    archived flag and the license GitHub detects."""
    if repos_file:
        return json.loads(Path(repos_file).read_text())
    headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    if os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {os.environ['GITHUB_TOKEN']}"
    repos, page = [], 1
    while True:
        url = f"https://api.github.com/orgs/{org}/repos?type=public&per_page=100&page={page}"
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
            batch = json.load(r)
        repos += batch
        if len(batch) < 100:
            break
        page += 1
    return [{
        "name": r["name"],
        "description": r.get("description") or "",
        "default_branch": r.get("default_branch") or "main",
        "archived": bool(r.get("archived")),
        "license": license_id(r),
    } for r in repos if not r.get("private")]


def license_id(repo):
    """The SPDX id GitHub detects. NOASSERTION means GitHub found a license
    file it cannot name; the sync then names the file instead."""
    spdx = (repo.get("license") or {}).get("spdx_id")
    return spdx if spdx and spdx != "NOASSERTION" else None


# Reading one upstream commit ------------------------------------------

class SyncError(Exception):
    """Upstream could not be read. The sync stops rather than write a
    state that a network failure has shaped."""


def git(*args, cwd=None, tries=1):
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    for attempt in range(tries):
        try:
            return subprocess.run(["git", *args], cwd=cwd, env=env, capture_output=True,
                                  text=True, check=True, timeout=300).stdout.strip()
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired):
            if attempt == tries - 1:
                raise
            time.sleep(2 ** (attempt + 1))


def fetch(url, ref, dest):
    """Check out one commit of a repo, with no history, into dest. ref is
    a branch ref or a full commit hash. Returns the commit hash."""
    git("init", "-q", str(dest))
    git("fetch", "-q", "--depth", "1", "--no-tags", url, ref, cwd=dest, tries=3)
    git("-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD", cwd=dest)
    return git("rev-parse", "HEAD", cwd=dest)


def strip_comments(src):
    """Lean source with comments removed. Block comments nest."""
    out, i, depth = [], 0, 0
    while i < len(src):
        if src.startswith("/-", i):
            depth, i = depth + 1, i + 2
        elif depth and src.startswith("-/", i):
            depth, i = depth - 1, i + 2
        elif depth:
            out.append("\n" if src[i] == "\n" else "")
            i += 1
        elif src.startswith("--", i):
            j = src.find("\n", i)
            i = len(src) if j < 0 else j
        else:
            out.append(src[i])
            i += 1
    return "".join(out)


IMPORT = re.compile(r"((?:public|private|meta)\s+)*import\s+(?:all\s+)?([^\s]+)")


def header_imports(src):
    """The modules a Lean file imports. The header ends at the first line
    that is not `module`, `prelude` or an import."""
    found = []
    for line in strip_comments(src).splitlines():
        line = line.strip()
        if not line or line in ("module", "prelude"):
            continue
        m = IMPORT.fullmatch(line)
        if not m:
            break
        found.append(m.group(2).replace("«", "").replace("»", ""))
    return found


def lean_modules(root, src_dir):
    """Map module name -> imports, for every .lean file under src_dir."""
    base = (root / src_dir).resolve()
    if not base.is_relative_to(root.resolve()) or not base.is_dir():
        return {}
    mods = {}
    for path in sorted(base.rglob("*.lean")):
        rel = path.relative_to(base)
        if path.is_symlink() or any(p.startswith(".") for p in rel.parts):
            continue
        if rel.parts[0] == "build" or rel.as_posix() == "lakefile.lean":
            continue
        mods[".".join(rel.with_suffix("").parts)] = header_imports(path.read_text(errors="replace"))
    return mods


def closure(starts, mods):
    seen, stack = set(), list(starts)
    while stack:
        m = stack.pop()
        if m in seen or m not in mods:
            continue
        seen.add(m)
        stack += mods[m]
    return seen


def top(module):
    return module.split(".")[0]


def lib_kind(lib):
    """main, spec, proofs or tests, from the last part of each root."""
    last = {r.split(".")[-1] for r in lib["roots"]}
    for kind, words in (("proofs", {"Proofs"}), ("spec", {"Spec"}), ("tests", {"Test", "Tests"})):
        if last <= words:
            return kind
    return "main"


def inspect(root):
    """What the sync needs to know about one checked-out commit. Returns
    a dict, with "error" set when the commit cannot join the workspace."""
    try:
        return read_commit(root)
    except (KeyError, TypeError, AttributeError) as e:
        return {"error": f"lakefile.toml is not in the shape the sync reads (at {e})"}


def read_commit(root):
    lakefile = root / "lakefile.toml"
    if not lakefile.is_file():
        if (root / "lakefile.lean").is_file():
            return {"error": "its lakefile is lakefile.lean; the sync reads lakefile.toml only"}
        return {"error": "no lakefile on its default branch"}
    try:
        lake = tomllib.loads(lakefile.read_text())
    except tomllib.TOMLDecodeError as e:
        return {"error": f"lakefile.toml does not parse: {e}"}
    tc_file = root / "lean-toolchain"
    toolchain = tc_file.read_text().strip() if tc_file.is_file() else ""
    if not TOOLCHAIN.fullmatch(toolchain):
        return {"error": f"lean-toolchain does not pin a Lean release: '{toolchain or 'missing'}'"}
    libs = []
    for lib in lake.get("lean_lib", []):
        roots = lib.get("roots") or [lib["name"]]
        libs.append({"name": lib["name"], "roots": [str(r) for r in roots],
                     "src": lib.get("srcDir", ".")})
    for lib in libs:
        lib["kind"] = lib_kind(lib)
    if not any(lib["kind"] == "main" for lib in libs):
        return {"error": "lakefile.toml has no main lean_lib (only Spec, Proofs or tests)"}
    exes = {exe.get("root", exe["name"]) for exe in lake.get("lean_exe", [])}
    mods = {}
    for src in sorted({lib["src"] for lib in libs} | {e.get("srcDir", ".") for e in lake.get("lean_exe", [])}):
        mods.update(lean_modules(root, src))
    for exe in exes:
        mods.pop(exe, None)

    def namespaces(kind):
        roots = [r for lib in libs if lib["kind"] == kind for r in lib["roots"]]
        return sorted({top(m) for m in closure(roots, mods)} | {top(r) for r in roots})

    comparator = {}
    if (root / "comparator.json").is_file():
        try:
            comparator = json.loads((root / "comparator.json").read_text())
        except json.JSONDecodeError:
            comparator = {}
    bar = None
    if (root / "bar.toml").is_file():
        try:
            bar = tomllib.loads((root / "bar.toml").read_text()).get("project", {}).get("status")
        except tomllib.TOMLDecodeError:
            bar = "unreadable"
    names = {top(m) for m in mods} | {top(r) for lib in libs for r in lib["roots"]}
    return {
        "package": lake["name"],
        "toolchain": toolchain,
        "libs": [{k: lib[k] for k in ("name", "kind", "roots")} for lib in libs],
        "requires": sorted(r["name"] for r in lake.get("require", [])),
        "namespaces": sorted(names),
        "main_namespaces": namespaces("main"),
        "proof_namespaces": namespaces("proofs"),
        "bar": bar,
        "spec_theorems": len(comparator.get("theorem_names") or []) or None,
        "license_file": next((p.name for p in sorted(root.iterdir())
                              if re.match(r"(?i)(licen[cs]e|copying)", p.name)), None),
    }


def discover_one(meta, cfg, old, tmp):
    """Inspect one repo's proposed pin, and its current pin when that
    differs. The proposed pin is its default branch head, unless sync.toml
    holds it."""
    name = meta["name"]
    url = f"{git_base(cfg)}/{name}"
    entry = {"meta": meta, "url": url, "hold": cfg["hold"].get(name)}
    try:
        out = git("ls-remote", url, f"refs/heads/{meta['default_branch']}", tries=3)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as e:
        raise SyncError(f"{name}: cannot list {url}: {getattr(e, 'stderr', '') or e}") from e
    if not out:
        entry["head"] = None
        entry["proposed"] = {"error": "its default branch has no commits yet"}
        return entry
    entry["head"] = out.split()[0]
    current = old.get("rev") if old.get("state") == "included" else None
    entry["was_included"] = current is not None
    want = entry["head"]
    if entry["hold"]:
        want = entry["hold"].get("rev", "")
        if not re.fullmatch(r"[0-9a-f]{40}", want):
            raise SyncError(f"sync.toml: hold.{name}.rev must be a full 40-character commit hash")
    for key, rev in (("proposed", want), ("current", current)):
        if key == "current" and (not rev or rev == want):
            continue
        dest = Path(tmp) / f"{name}-{key}"
        try:
            got = fetch(url, rev, dest)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as e:
            if key == "proposed":
                raise SyncError(f"{name}: cannot fetch {rev}: {getattr(e, 'stderr', '') or e}") from e
            # The current pin may have been force-pushed away upstream.
            entry[key] = {"rev": rev, "error": f"its current pin {rev[:12]} can no longer be fetched"}
            continue
        entry[key] = dict(inspect(dest), rev=got)
    return entry


def discover(cfg, previous, repos_file=None):
    """List the org and inspect every repo it does not exclude."""
    prev = {r["repo"]: r for r in previous.get("repos", [])}
    metas = [m for m in list_org(cfg["org"], repos_file) if m["name"] not in cfg["exclude"]]
    with tempfile.TemporaryDirectory() as tmp, ThreadPoolExecutor(8) as pool:
        jobs = {m["name"]: pool.submit(discover_one, m, cfg, prev.get(m["name"], {}), tmp)
                for m in metas}
        return {name: jobs[name].result() for name in sorted(jobs)}


def apply_keep(found, keep):
    """--keep-pin: each named repo keeps its current pin instead of the one
    discover() proposed, or stays out of the workspace if it has none. It
    works on what discover() found, so it needs no network."""
    for name in keep:
        e = found.get(name)
        if not e or not e.get("head"):
            continue
        if "current" in e:
            e["proposed"] = e.pop("current")
            e["kept"] = True
        elif not e.get("was_included"):
            e["proposed"] = {"rev": e["proposed"].get("rev"),
                             "error": "its default branch head fails to build in the workspace"}
    return found


# Deciding the workspace -----------------------------------------------

def version(toolchain):
    m = TOOLCHAIN.fullmatch(toolchain)
    if not m:
        return (0,)
    major, minor, patch, rc = m.groups()
    # A release sorts after its release candidates.
    return (int(major), int(minor), int(patch), int(rc) if rc else 10**6)


def pick_toolchain(found, current, forced=None):
    if forced:
        return forced
    counts = Counter(e["proposed"]["toolchain"] for e in found.values()
                     if "toolchain" in e.get("proposed", {}))
    if not counts:
        return current
    return max(counts, key=lambda t: (counts[t], t == current, version(t)))


def problem(info, accepted, toolchain):
    """Why this commit cannot join the workspace beside the repos already
    accepted, or None."""
    if info.get("error"):
        return info["error"]
    if info["toolchain"] != toolchain:
        return f"it uses {info['toolchain']}, and the workspace uses {toolchain}"
    clash = OWN_MODULES & set(info["namespaces"])
    if clash:
        return f"it defines module {sorted(clash)[0]}, which this repo uses"
    for other in accepted:
        if other["package"] == info["package"]:
            return f"its Lake package name {info['package']} is also the package name of {other['repo']}"
        for mine, theirs in ((info["main_namespaces"], other["namespaces"]),
                             (info["namespaces"], other["main_namespaces"])):
            shared = sorted(set(mine) & set(theirs))
            if shared:
                return f"top-level module {shared[0]} is also used by {other['repo']}"
    return None


def decide(found, previous, cfg, hold_joint=None):
    """The new state: the workspace toolchain, and one record per repo."""
    prev = {r["repo"]: r for r in previous.get("repos", [])}
    current_tc = previous.get("toolchain") or (ROOT / "lean-toolchain").read_text().strip()
    toolchain = pick_toolchain(found, current_tc, cfg.get("toolchain"))
    # Repos already in the workspace go first, so a newcomer cannot push
    # one out by taking its module names.
    order = sorted(found, key=lambda n: (prev.get(n, {}).get("state") != "included", n))
    accepted, records = [], {}
    for name in order:
        e = found[name]
        meta = e["meta"]
        rec = {
            "repo": name,
            "url": e["url"],
            "description": meta.get("description", ""),
            "archived": meta.get("archived", False),
            "branch": meta.get("default_branch", "main"),
            "head": e["head"],
            "license": meta.get("license"),
        }
        options = [("proposed", e["proposed"])]
        if "current" in e:
            options.append(("current", e["current"]))
        reasons = []
        for key, info in options:
            why = problem(info, accepted, toolchain)
            if why:
                reasons.append(why)
                continue
            rec.update(state="included", **{k: v for k, v in info.items() if k != "error"})
            if not rec["license"] and info.get("license_file"):
                rec["license"] = f"see {info['license_file']}"
            rec.pop("license_file", None)
            if key == "current":
                what = "commit sync.toml holds it at" if e.get("hold") else "head"
                rec["note"] = f"its {what} cannot join the workspace, because {reasons[0]}"
            elif e.get("kept"):
                what = "commit sync.toml holds it at" if e.get("hold") else "head"
                rec["note"] = f"its {what} fails to build in the workspace"
            elif e.get("hold"):
                rec["note"] = f"sync.toml holds it: {e['hold'].get('reason', 'no reason given')}"
            accepted.append(rec)
            break
        else:
            rec.update(state="pending", reason=reasons[0])
            # Only whether it can join matters, so a new commit that leaves
            # the reason as it was changes nothing here.
            del rec["head"]
            proposed = e["proposed"]
            if not rec["license"] and proposed.get("license_file"):
                rec["license"] = f"see {proposed['license_file']}"
        records[name] = rec
    if hold_joint is None:
        # A library held out of AnthologyProofs stays out while its pin
        # does not move, so an unchanged upstream reproduces the last state.
        hold_joint = {r["repo"] for r in accepted
                      if prev.get(r["repo"], {}).get("joint_note") and prev[r["repo"]].get("rev") == r["rev"]}
    for rec in accepted:
        others = {n for o in accepted if o is not rec for n in o["namespaces"]}
        has_proofs = any(lib["kind"] == "proofs" for lib in rec["libs"])
        rec["joint_proofs"] = has_proofs and not (set(rec["proof_namespaces"]) & others)
        if rec["joint_proofs"] and rec["repo"] in hold_joint:
            rec["joint_proofs"] = False
            rec["joint_note"] = "the joint proof build fails with it"
    state = {
        "org": cfg["org"],
        "toolchain": toolchain,
        "synced": previous.get("synced"),
        "repos": [records[n] for n in sorted(records)],
    }
    if strip_date(state) != strip_date(previous):
        state["synced"] = datetime.date.today().isoformat()
    return state


def strip_date(state):
    return {k: v for k, v in state.items() if k != "synced"}


# Rendering ------------------------------------------------------------

def included(state):
    return [r for r in state["repos"] if r["state"] == "included"]


def main_modules(rec):
    return [m for lib in rec["libs"] if lib["kind"] == "main" for m in lib["roots"]]


def proof_modules(rec):
    return [m for lib in rec["libs"] if lib["kind"] == "proofs" for m in lib["roots"]]


def wrap(words, prefix="-- ", width=72):
    lines, line = [], prefix
    for w in words:
        if len(line) + len(w) + 1 > width and line != prefix:
            lines.append(line.rstrip())
            line = prefix
        line += w + " "
    lines.append(line.rstrip())
    return lines


def render_lakefile(state):
    out = [f"# {GENERATED}", "# To change what is pinned, edit sync.toml or run the sync.",
           'name = "proven-commons"', 'version = "0.1.0"',
           'defaultTargets = ["Anthology", "AnthologyProofs"]', "",
           "[[lean_lib]]", 'name = "Anthology"', "", "[[lean_lib]]", 'name = "AnthologyProofs"']
    for rec in included(state):
        out += ["", "[[require]]", f'name = "{rec["package"]}"', f'git = "{rec["url"]}"', f'rev = "{rec["rev"]}"']
    return "\n".join(out) + "\n"


def render_imports(pairs):
    width = max((len(m) for m, _ in pairs), default=0)
    return [f"import {m.ljust(width)}  -- {repo}" for m, repo in pairs]


def render_anthology(state):
    head = [
        "-- Aggregator module for the Proven-Commons anthology.",
        f"-- {GENERATED}",
        "-- Building this module builds the main library of every package in the",
        "-- workspace. Each import is a main library module of the upstream repo",
        "-- in its comment. One repo can provide more than one, as utf provides",
        "-- Utf8 and Utf16.",
    ]
    pairs = [(m, rec["repo"]) for rec in included(state) for m in main_modules(rec)]
    return "\n".join(head + render_imports(pairs)) + "\n"


def render_proofs(state):
    head = [
        "-- Aggregator module for the proof libraries of the anthology.",
        f"-- {GENERATED}",
        "-- A package's proof library is imported here once every top-level",
        "-- module name it uses is unique in the workspace, and the joint",
        "-- build succeeds with it. Until then, scripts/build-all.sh builds it",
        "-- one package at a time. Upstream proof libraries named plain",
        "-- `Proofs` and `Spec` collide across packages, and several declare",
        "-- the same `Spec.*` theorem names: see issue #4.",
    ]
    recs = included(state)
    pairs = [(m, rec["repo"]) for rec in recs if rec["joint_proofs"] for m in proof_modules(rec)]
    for title, repos in outside(recs):
        head += ["--", f"-- Not imported yet, because {title}:"]
        head += wrap([w + "," for w in repos[:-1]] + [repos[-1] + "."])
    return "\n".join(head + render_imports(pairs)) + "\n"


def outside(recs):
    """The packages whose proof library AnthologyProofs leaves out, by
    reason: (reason, repos) for each reason that has any."""
    collide = [r["repo"] for r in recs if proof_modules(r) and not r["joint_proofs"] and not r.get("joint_note")]
    held = [r["repo"] for r in recs if r.get("joint_note")]
    return [(why, repos) for why, repos in (
        ("their module names collide", collide),
        ("the joint build fails with them, though their module names are unique", held)) if repos]


def audit_cell(rec, audit):
    a = audit.get("packages", {}).get(rec["package"])
    if not a or a.get("rev") != rec["rev"]:
        return "not audited at this pin"
    if a.get("error"):
        return f"audit failed: {a['error']}"
    parts = [count(a["theorems"], "theorem")]
    if a.get("examples"):
        parts[0] += f", {count(a['examples'], '`example`')} §"
    bad = []
    if a["sorry"]:
        bad.append(f"{count(len(a['sorry']), 'declaration')} {'uses' if len(a['sorry']) == 1 else 'use'} `sorry`")
    if a.get("sorry_in_build"):
        bad.append(f"the build warns of `sorry` at {count(len(a['sorry_in_build']), 'place')}")
    for ax, names in sorted(a["nonstandard"].items()):
        bad.append(f"{count(len(names), 'declaration')} {'uses' if len(names) == 1 else 'use'} axiom `{ax}`")
    if a["package_axioms"]:
        bad.append(f"declares axioms {', '.join(f'`{x}`' for x in a['package_axioms'])}")
    parts.append("; ".join(bad) if bad else "standard axioms only")
    spec = a.get("spec")
    if spec:
        parts.append(f"{'all' if spec['proved'] == spec['named'] else str(spec['proved']) + ' of'} "
                     f"{spec['named']} theorems named in comparator.json proved")
    return "; ".join(parts)


def bar_cell(rec):
    return {"in-progress": "in progress", "verified": "verified", None: "no bar.toml"}.get(
        rec.get("bar"), str(rec.get("bar")))


def describe(rec):
    desc = rec["description"].replace("|", "\\|") or "(no description)"
    if re.search(r"(?i)\bverified\b", desc) and rec.get("bar") != "verified":
        desc += " †"
    if rec.get("archived"):
        desc += " (archived upstream)"
    return desc


def repo_cell(rec):
    cell = f"[{rec['repo']}]({rec['url']})"
    if rec.get("package") and rec["package"] != rec["repo"]:
        cell += f" (package `{rec['package']}`)"
    return cell


def count(n, word, plural=None):
    return f"{n} {word if n == 1 else (plural or word + 's')}"


def render_block(state, audit):
    recs, pending = included(state), [r for r in state["repos"] if r["state"] == "pending"]
    org = state["org"]
    out = [BEGIN, "",
           f"Snapshot of the [{org}](https://github.com/{org}) org, synced {state['synced']}: "
           f"{count(len(state['repos']), 'library repo')}, {len(recs)} of them in the workspace. "
           f"Each workspace library is pinned to a commit of its upstream default branch whose "
           f"`lean-toolchain` is `{state['toolchain']}`, the toolchain of this workspace."]
    needs = [r for r in recs if r["requires"]]
    out[-1] += (" None of them requires another package." if not needs else
                " Libraries that require other packages: " +
                "; ".join(f"{r['repo']} ({', '.join(r['requires'])})" for r in needs) + ".")
    out += ["", "| Repo | Upstream description | Pinned commit | Proof audit | Verified bar | License |",
            "| --- | --- | --- | --- | --- | --- |"]
    for rec in recs:
        pin = f"[`{rec['rev'][:12]}`]({rec['url']}/commit/{rec['rev']})"
        if rec["rev"] != rec["head"]:
            pin += " ‡"
        out.append(f"| {repo_cell(rec)} | {describe(rec)} | {pin} | {audit_cell(rec, audit)} "
                   f"| {bar_cell(rec)} | {rec.get('license') or 'none'} |")
    notes = []
    if any(describe(r).count("†") for r in state["repos"]):
        notes.append("† The upstream description says verified, but the project has not met the "
                     f"[verified bar](https://github.com/{org}/mission#the-verified-bar). "
                     "Read it as the project's goal, not as a checked status.")
    if any(audit.get("packages", {}).get(r["package"], {}).get("examples") for r in recs):
        notes.append("§ An `example` has no name, so `#print axioms` cannot audit it. The build "
                     "compiles it, which checks it, and the audit reads the build log for `sorry`.")
    for rec in recs:
        note = rec.get("note")
        if rec["rev"] != rec["head"]:
            notes.append(f"‡ {rec['repo']} is pinned behind its default branch head "
                         f"`{rec['head'][:12]}`" + (f": {note}." if note else "."))
        elif note:
            notes.append(f"{rec['repo']}: {note}.")
    if notes:
        out += [""] + [n for note in notes for n in (note, "")][:-1]
    if pending:
        out += ["", "Not in the workspace yet:", "",
                "| Repo | Upstream description | Why not yet | License |",
                "| --- | --- | --- | --- |"]
        for rec in pending:
            out.append(f"| {repo_cell(rec)} | {describe(rec)} | {rec['reason'][:1].upper()}{rec['reason'][1:]} "
                       f"| {rec.get('license') or 'none'} |")
    joint = [r["repo"] for r in recs if r["joint_proofs"]]
    out += ["", f"Joint proof build: `AnthologyProofs` imports the proof libraries of "
            f"{count(len(joint), 'package')}" + (f" ({', '.join(joint)})" if joint else "") + "."]
    for why, repos in outside(recs):
        one = len(repos) == 1
        if why.startswith("their module"):
            out[-1] += (f" {count(len(repos), 'package')} ({', '.join(repos)}) "
                        f"{'has a proof library whose' if one else 'have proof libraries whose'} "
                        "top-level module names are also used by other packages.")
        else:
            out[-1] += (f" {count(len(repos), 'package')} ({', '.join(repos)}) "
                        f"{'has a proof library' if one else 'have proof libraries'} with unique module "
                        "names that the joint build still fails with, most likely because two packages "
                        "declare the same theorem name.")
    left_out = [r for r in recs if proof_modules(r) and not r["joint_proofs"]]
    if left_out:
        out[-1] += (f" `scripts/build-all.sh` builds {'it on its own' if len(left_out) == 1 else 'those one package at a time'}."
                    " See issue #4.")
    out += ["", END]
    return "\n".join(out)


def render_readme(state, audit, text):
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit("README.md has no generated block markers")
    return text[:start] + render_block(state, audit) + text[end + len(END):]


def rendered(state, audit, readme_text):
    """Every file the sync writes, as path -> text."""
    return {
        "repos.json": json.dumps(state, indent=2, ensure_ascii=False) + "\n",
        "lean-toolchain": state["toolchain"] + "\n",
        "lakefile.toml": render_lakefile(state),
        "Anthology.lean": render_anthology(state),
        "AnthologyProofs.lean": render_proofs(state),
        "README.md": render_readme(state, audit, readme_text),
    }


def load_json(path, default):
    return json.loads(path.read_text()) if path.is_file() else default


# Reporting ------------------------------------------------------------

def report(old, new, excluded=()):
    """A Markdown summary of what the sync changed, for a pull request."""
    before = {r["repo"]: r for r in old.get("repos", [])}
    after = {r["repo"]: r for r in new["repos"]}
    lines = []
    if old.get("toolchain") and old["toolchain"] != new["toolchain"]:
        lines.append(f"- Workspace toolchain: `{old.get('toolchain')}` → `{new['toolchain']}`.")
    for name in sorted(set(before) | set(after)):
        b, a = before.get(name), after.get(name)
        if a is None:
            was = f" (it was pinned at `{b['rev'][:12]}`)" if b.get("state") == "included" else ""
            why = "sync.toml now excludes it" if name in excluded else "it is no longer a public repo in the org"
            lines.append(f"- **{name}** leaves the anthology, because {why}{was}.")
            continue
        url = a["url"]
        if a["state"] == "included":
            if not b or b["state"] != "included":
                lines.append(f"- **{name}** joins the workspace at [`{a['rev'][:12]}`]({url}/commit/{a['rev']}).")
            elif b["rev"] != a["rev"]:
                lines.append(f"- **{name}**: [`{b['rev'][:12]}` → `{a['rev'][:12]}`]"
                             f"({url}/compare/{b['rev']}...{a['rev']}).")
            if a.get("note") and a.get("note") != (b or {}).get("note"):
                where = f"stays at `{a['rev'][:12]}`" if a["rev"] != a["head"] else "follows its head"
                lines.append(f"- **{name}** {where}: {a['note']}.")
            was_joint = (b or {}).get("joint_proofs")
            because = f", because {a['joint_note']}" if a.get("joint_note") else ""
            if a.get("joint_proofs") and not was_joint:
                lines.append(f"- **{name}**: its proof library joins `AnthologyProofs`.")
            elif was_joint and not a.get("joint_proofs"):
                lines.append(f"- **{name}**: its proof library leaves `AnthologyProofs`{because}.")
            elif because and a.get("joint_note") != (b or {}).get("joint_note"):
                lines.append(f"- **{name}**: its proof library stays out of `AnthologyProofs`{because}.")
        elif b and b["state"] == "included":
            lines.append(f"- **{name}** leaves the workspace: {a['reason']}.")
        elif not b:
            lines.append(f"- **{name}** is new in the org, not in the workspace yet: {a['reason']}.")
        elif b.get("reason") != a["reason"]:
            lines.append(f"- **{name}** is still not in the workspace: {a['reason']}.")
    return "\n".join(lines) if lines else "- No change to the pins or the repo list."


# Main -----------------------------------------------------------------

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--report")
    ap.add_argument("--keep-pin", nargs="*", default=[])
    ap.add_argument("--hold-joint", nargs="*", default=None)
    found_io = ap.add_mutually_exclusive_group()
    found_io.add_argument("--save-found")
    found_io.add_argument("--found")
    ap.add_argument("--previous", default=str(STATE))
    ap.add_argument("--repos-file", default=os.environ.get("SYNC_REPOS_FILE"),
                    help="JSON list of repos to use instead of asking GitHub (or SYNC_REPOS_FILE)")
    args = ap.parse_args(argv)
    previous = load_json(Path(args.previous), {})
    cfg = None if args.render else load_config()
    if args.render:
        state = load_json(STATE, None)
        if state is None:
            raise SystemExit("no repos.json to render from")
    else:
        if args.found:
            found = json.loads(Path(args.found).read_text())
        else:
            try:
                found = discover(cfg, previous, args.repos_file)
            except SyncError as e:
                print(f"sync stopped, nothing written: {e}", file=sys.stderr)
                return 2
            if args.save_found:
                Path(args.save_found).write_text(json.dumps(found, indent=1) + "\n")
        found = apply_keep(found, set(args.keep_pin))
        hold = None if args.hold_joint is None else set(args.hold_joint)
        state = decide(found, previous, cfg, hold)
    files = rendered(state, load_json(AUDIT, {}), README.read_text())
    changed = [p for p, text in files.items()
               if not (ROOT / p).is_file() or (ROOT / p).read_text() != text]
    excluded = () if args.render else cfg["exclude"]
    if args.report:
        Path(args.report).write_text(report(previous, state, excluded) + "\n")
    if args.check:
        for p in changed:
            print(f"{p}: out of date")
        if changed:
            print("Run scripts/sync.py, then lake update, the build and scripts/audit.py.")
            return 1
        print("Up to date with upstream.")
        return 0
    for p in changed:
        (ROOT / p).write_text(files[p])
        print(f"wrote {p}")
    if not changed:
        print("No changes.")
    print(report(previous, state, excluded))
    return 0


if __name__ == "__main__":
    sys.exit(main())
